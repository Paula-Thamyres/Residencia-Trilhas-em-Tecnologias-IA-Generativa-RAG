def chunk_fixo(texto, tamanho, overlap):
    splitter = CharacterTextSplitter(
        separator="",
        chunk_size=tamanho,
        chunk_overlap=overlap,
        length_function=len,
        keep_separator=False
    )

    return splitter.split_text(texto)


