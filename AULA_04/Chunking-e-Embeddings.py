def grupo_7(texto):
    texto = texto.replace("\r\n", "\n")

    paragrafos = re.split(r"\n\s*\n+", texto.strip())

    return [
        paragrafo.strip()
        for paragrafo in paragrafos
        if paragrafo.strip()
    ]


# ------------------------------------------------------------
# TESTE 8 — POR SENTENÇA, AGRUPANDO 3
# ------------------------------------------------------------

def grupo_8(texto):
    texto = texto.replace("\r\n", "\n").strip()

    sentencas = re.split(
        r"(?<=[.!?])\s+",
        texto
    )

    sentencas = [
        sentenca.strip()
        for sentenca in sentencas
        if sentenca.strip()
    ]

    chunks = []

    for i in range(0, len(sentencas), 3):
        grupo = sentencas[i:i + 3]

        chunks.append(
            " ".join(grupo)
        )

    return chunks


