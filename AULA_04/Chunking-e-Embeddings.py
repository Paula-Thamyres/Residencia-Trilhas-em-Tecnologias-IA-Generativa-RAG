def grupo_9(texto):
    splitter = RecursiveCharacterTextSplitter(
        chunk_size=500,
        chunk_overlap=0,
        length_function=len,
        separators=[
            "\n\n",
            "\n",
            " ",
            ""
        ]
    )

    return splitter.split_text(texto)


# ------------------------------------------------------------
# TESTE 10 — SEÇÕES / HEADINGS MARKDOWN
# ------------------------------------------------------------

def grupo_10(texto):

    # Alguns headings dos arquivos estão escritos como:
    # \## Título
    #
    # O splitter Markdown espera:
    # ## Título
    #
    # Então corrigimos SOMENTE a marcação do heading
    # para que o splitter consiga reconhecê-la.

    texto_normalizado = re.sub(
        r"^(\\)(#{1,6})(\s+)",
        r"\2\3",
        texto,
        flags=re.MULTILINE
    )

    headers_to_split_on = [
        ("#", "Título"),
        ("##", "Seção"),
        ("###", "Subseção"),
        ("####", "Subsubseção")
    ]

    splitter = MarkdownHeaderTextSplitter(
        headers_to_split_on=headers_to_split_on,
        strip_headers=False
    )

    documentos = splitter.split_text(texto_normalizado)

    return [
        documento.page_content.strip()
        for documento in documentos
        if documento.page_content.strip()
    ]


