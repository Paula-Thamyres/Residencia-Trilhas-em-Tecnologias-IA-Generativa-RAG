def similaridade_cosseno(vetor_a, vetor_b):

    produto = np.dot(vetor_a, vetor_b)

    norma_a = np.linalg.norm(vetor_a)
    norma_b = np.linalg.norm(vetor_b)

    if norma_a == 0 or norma_b == 0:
        return 0.0

    return produto / (norma_a * norma_b)



